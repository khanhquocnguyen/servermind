#!/usr/bin/env bash
# tunnel.sh — Manage this machine's Cloudflare Tunnel (the cloudflared container in docker-compose.yml).
#
#   bash tunnel.sh zone <zone>                Get an origin cert for a Cloudflare zone (opens a browser login) → zones/<zone>.pem
#   bash tunnel.sh init [credentials.json]    Create a tunnel named after this machine, or adopt an existing one from its
#                                             credentials file → credentials.json + .env. Run once per machine.
#   bash tunnel.sh route <hostname>           Point <hostname> at this tunnel (proxied CNAME, overwrites the old record).
#                                             The zone is picked from zones/*.pem. Run once per hostname.
#   bash tunnel.sh status                     Tunnel id, container state, routed zones.
#
# Needs the cloudflared CLI on this machine for zone/init/route (brew install cloudflared, or the Cloudflare apt repo).
# Runs on macOS bash 3.2 too (dev laptops), so no bash-4 features.

set -euo pipefail

info() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33m[!] %s\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m[✓] %s\033[0m\n' "$*"; }
die()  { printf '\033[1;31m[x] %s\033[0m\n' "$*" >&2; exit 1; }

DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ZONES="$DIR/zones"
CREDS="$DIR/credentials.json"
ENVF="$DIR/.env"

need_cli() { command -v cloudflared >/dev/null || die "cloudflared CLI is required (brew install cloudflared / Cloudflare apt repo)."; }
lower() { printf '%s' "$1" | tr '[:upper:]' '[:lower:]'; }
tunnel_id() { [[ -f "$ENVF" ]] && sed -n 's/^TUNNEL_ID=//p' "$ENVF" | tail -n1; }

# ---------------------------------------------------------------------------
cmd_zone() {
  local zone d bak=""
  zone=$(lower "${1:-}"); zone=${zone#*://}; zone=${zone%%/*}
  [[ "$zone" =~ ^([a-z0-9-]+\.)+[a-z]{2,}$ ]] || die "Usage: bash tunnel.sh zone <zone>   (e.g. example.com)"
  need_cli
  mkdir -p "$ZONES"
  [[ -f "$ZONES/$zone.pem" ]] && { ok "zones/$zone.pem already exists."; return; }
  # `cloudflared tunnel login` always writes ~/.cloudflared/cert.pem and refuses if it exists: park it, then restore.
  d="$HOME/.cloudflared"; mkdir -p "$d"
  if [[ -f "$d/cert.pem" ]]; then bak="$d/cert.pem.bak.$$"; mv "$d/cert.pem" "$bak"; fi
  restore() { if [[ -n "$bak" && -f "$bak" ]]; then mv "$bak" "$d/cert.pem"; fi; }
  info "Log in to Cloudflare and pick the zone $zone"
  if cloudflared tunnel login && [[ -f "$d/cert.pem" ]]; then
    install -m 600 "$d/cert.pem" "$ZONES/$zone.pem"; rm -f "$d/cert.pem"; restore
    ok "zones/$zone.pem written (600)."
  else
    rm -f "$d/cert.pem"; restore; die "cloudflared tunnel login did not finish."
  fi
}

# ---------------------------------------------------------------------------
write_env() {
  local id=$1
  umask 077
  { echo "# GENERATED by tunnel.sh init"; echo "TUNNEL_ID=$id"; echo "TUNNEL_UID=$(id -u)"; echo "TUNNEL_GID=$(id -g)"; } > "$ENVF"
  ok ".env written (tunnel $id, uid $(id -u))."
}

cmd_init() {
  local src=${1:-} id name cert
  if [[ -f "$CREDS" ]]; then
    id=$(sed -n 's/.*"TunnelID" *: *"\([^"]*\)".*/\1/p' "$CREDS")
    [[ -n "$id" ]] || die "credentials.json exists but has no TunnelID — move it away and rerun."
    warn "credentials.json already exists (tunnel $id); keeping it."
    write_env "$id"; return
  fi
  if [[ -n "$src" ]]; then
    info "Adopt existing tunnel from $src"
    [[ -f "$src" ]] || die "No such file: $src"
    id=$(sed -n 's/.*"TunnelID" *: *"\([^"]*\)".*/\1/p' "$src")
    [[ -n "$id" ]] || die "$src has no TunnelID — is it a tunnel credentials file (~/.cloudflared/<id>.json)?"
    install -m 600 "$src" "$CREDS"
  else
    need_cli
    cert=$(ls "$ZONES"/*.pem 2>/dev/null | head -n1 || true)
    [[ -n "$cert" ]] || die "No zone cert yet — run: bash tunnel.sh zone <zone>"
    name=$(hostname -s | tr '[:upper:]' '[:lower:]')
    read -rp "Tunnel name [$name]: " ans; name=${ans:-$name}
    info "Create tunnel $name"
    cloudflared tunnel --origincert "$cert" create --credentials-file "$CREDS" "$name"
    chmod 600 "$CREDS"
    id=$(sed -n 's/.*"TunnelID" *: *"\([^"]*\)".*/\1/p' "$CREDS")
    [[ -n "$id" ]] || die "Tunnel created but credentials.json has no TunnelID."
  fi
  ok "credentials.json written (600)."
  write_env "$id"
  echo "  Next: docker compose up -d   then   bash tunnel.sh route <hostname>"
}

# ---------------------------------------------------------------------------
cmd_route() {
  local host zone="" z out id
  host=$(lower "${1:-}"); host=${host#*://}; host=${host%%/*}
  [[ "$host" =~ ^([a-z0-9-]+\.)+[a-z]{2,}$ ]] || die "Usage: bash tunnel.sh route <hostname>"
  need_cli
  id=$(tunnel_id); [[ -n "$id" ]] || die "No tunnel yet — run: bash tunnel.sh init"
  # Longest zone in zones/ that the host belongs to.
  for f in "$ZONES"/*.pem; do
    [[ -f "$f" ]] || continue
    z=$(basename "$f" .pem)
    if [[ "$host" == "$z" || "$host" == *".$z" ]] && [[ ${#z} -gt ${#zone} ]]; then zone=$z; fi
  done
  [[ -n "$zone" ]] || die "No zone cert covers $host — run: bash tunnel.sh zone <its zone>"
  # `route dns` writes into the zone of the cert it is given; the wrong cert creates "<host>.<other zone>" and still
  # reports success. Hence one cert per zone, and the check below.
  out=$(cloudflared tunnel --origincert "$ZONES/$zone.pem" route dns --overwrite-dns "$id" "$host" 2>&1) || { echo "$out" >&2; die "route dns failed."; }
  echo "$out" | tail -n 3
  if echo "$out" | grep -q "$host\."; then
    die "The record was created under the wrong name (zones/$zone.pem is not zone $zone). Delete it in the dashboard, then: rm zones/$zone.pem && bash tunnel.sh zone $zone"
  fi
  ok "$host → tunnel $id (proxied CNAME, zone $zone)"
}

# ---------------------------------------------------------------------------
cmd_status() {
  local id; id=$(tunnel_id)
  echo "Tunnel    : ${id:-not initialised (bash tunnel.sh init)}"
  if command -v docker >/dev/null && docker ps --format '{{.Names}}' 2>/dev/null | grep -qx cloudflared; then
    echo "Container : running"
    docker logs --since 24h cloudflared 2>&1 | grep -c "Registered tunnel connection" | sed 's/^/Connected : /; s/$/ connection(s) registered in the last 24h/'
  else
    echo "Container : not running (docker compose up -d)"
  fi
  local zs; zs=$(ls "$ZONES"/*.pem 2>/dev/null | xargs -n1 basename 2>/dev/null | sed 's/\.pem$//' | paste -sd' ' - || true)
  echo "Zones     : ${zs:-none (bash tunnel.sh zone <zone>)}"
}

case "${1:-}" in
  zone)   shift; cmd_zone "$@" ;;
  init)   shift; cmd_init "$@" ;;
  route)  shift; cmd_route "$@" ;;
  status) cmd_status ;;
  *) sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
